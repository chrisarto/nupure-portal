'use client';

import { useState, useEffect } from 'react';
import { useRouter } from 'next/navigation';
import { createClient } from '@/lib/supabase/client';
import styles from './login.module.css';

export default function LoginPage() {
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [success, setSuccess] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [mode, setMode] = useState<'login' | 'recovery'>('login');
  
  const router = useRouter();
  const supabase = createClient();

  useEffect(() => {
    // Check if we arrived via a recovery link
    const { data: { subscription } } = supabase.auth.onAuthStateChange((event) => {
      if (event === 'PASSWORD_RECOVERY') {
        setMode('recovery');
      }
    });
    
    // Also check URL hash directly to handle non-PKCE implicit links generated by Admin API
    const hash = typeof window !== 'undefined' ? window.location.hash : '';
    if (hash.includes('type=recovery') || hash.includes('type=invite')) {
      const hashString = hash.substring(1);
      const params = new URLSearchParams(hashString);
      const accessToken = params.get('access_token');
      const refreshToken = params.get('refresh_token');
      
      if (accessToken && refreshToken) {
        // Manually establish the session from the URL hash tokens
        supabase.auth.setSession({
          access_token: accessToken,
          refresh_token: refreshToken,
        }).then(({ error }) => {
          if (!error) setMode('recovery');
        });
      } else if (accessToken) {
        // Some invite links only have access_token
        supabase.auth.setSession({
          access_token: accessToken,
          refresh_token: '',
        }).then(({ error }) => {
          if (!error) setMode('recovery');
        });
      } else {
        setMode('recovery');
      }
    }

    return () => subscription.unsubscribe();
  }, [supabase]);

  const handleLogin = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    setError(null);

    try {
      const { error } = await supabase.auth.signInWithPassword({
        email,
        password,
      });

      if (error) throw error;

      router.push('/dashboard');
      router.refresh();
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Failed to sign in');
    } finally {
      setLoading(false);
    }
  };

  const handleUpdatePassword = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    setError(null);
    setSuccess(null);

    try {
      const { error } = await supabase.auth.updateUser({
        password: password,
      });

      if (error) throw error;

      setSuccess('Password updated successfully! Redirecting...');
      setTimeout(() => {
        router.push('/dashboard');
        router.refresh();
      }, 2000);
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Failed to update password');
      setLoading(false);
    }
  };

  return (
    <div className={styles.container}>
      <div className={styles.card}>
        <div className={styles.header}>
          <div className={styles.logo}>
            <img 
              src="/icon.png" 
              alt="MJ Hygiene" 
              style={{ maxHeight: '60px', objectFit: 'contain' }}
            />
          </div>
          <h1 className={styles.title}>{mode === 'recovery' ? 'Set New Password' : 'Welcome Back'}</h1>
          <p className={styles.subtitle}>
            {mode === 'recovery' ? 'Please choose a new password for your account' : 'Sign in to the Nu-Pure Beverages Compliance Portal'}
          </p>
        </div>

        {error && <div className={styles.error}>{error}</div>}
        {success && <div className={styles.success} style={{ padding: '0.75rem', backgroundColor: '#d1fae5', color: '#065f46', borderRadius: '4px', marginBottom: '1rem', fontSize: '0.875rem' }}>{success}</div>}

        {mode === 'recovery' ? (
          <form className={styles.form} onSubmit={handleUpdatePassword}>
            <div className={styles.field}>
              <label className={styles.label} htmlFor="new-password">New Password</label>
              <input
                id="new-password"
                type="password"
                className={styles.input}
                placeholder="••••••••"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                required
                minLength={6}
              />
            </div>

            <button type="submit" className={styles.button} disabled={loading}>
              {loading ? 'Updating...' : 'Set Password & Continue'}
            </button>
          </form>
        ) : (
          <form className={styles.form} onSubmit={handleLogin}>
            <div className={styles.field}>
              <label className={styles.label} htmlFor="email">Email address</label>
              <input
                id="email"
                type="email"
                className={styles.input}
                placeholder="name@company.com"
                value={email}
                onChange={(e) => setEmail(e.target.value)}
                required
              />
            </div>

            <div className={styles.field}>
              <label className={styles.label} htmlFor="password">Password</label>
              <input
                id="password"
                type="password"
                className={styles.input}
                placeholder="••••••••"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                required
              />
            </div>

            <button type="submit" className={styles.button} disabled={loading}>
              {loading ? 'Signing in...' : 'Sign In'}
            </button>
          </form>
        )}
      </div>
    </div>
  );
}
